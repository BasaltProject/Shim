  public static void fill(UIDefaults t) {
    for (String line : kData) {
      String[] f = line.split("\\|", -1);
      String key = f[0];
      switch (f[1]) {
        case "C":
          t.put(key, new ColorUIResource(new Color(Integer.parseInt(f[2]))));
          break;
        case "F":
          t.put(key, new FontUIResource(f[2], Integer.parseInt(f[3]), Integer.parseInt(f[4])));
          break;
        case "I": {
          String[] i = f[2].split(",");
          t.put(key, new InsetsUIResource(Integer.parseInt(i[0]), Integer.parseInt(i[1]), Integer.parseInt(i[2]),
              Integer.parseInt(i[3])));
          break;
        }
        case "D": {
          String[] d = f[2].split(",");
          t.put(key, new DimensionUIResource(Integer.parseInt(d[0]), Integer.parseInt(d[1])));
          break;
        }
        case "N":
          t.put(key, Integer.valueOf(f[2]));
          break;
        case "L":
          t.put(key, Long.valueOf(f[2]));
          break;
        case "B":
          t.put(key, Boolean.valueOf(f[2]));
          break;
        case "H":
          t.put(key, Character.valueOf((char) Integer.parseInt(f[2])));
          break;
        default:
          t.put(key, f.length > 2 ? f[2].replace("\\n", "\n") : "");
          break;
      }
    }
  }

  private static java.util.Hashtable<String, Tag> tagHashtable;
  private static java.util.Hashtable<String, Attribute> attHashtable;

  private static synchronized void init() {
    if (tagHashtable != null) {
      return;
    }
    tagHashtable = new java.util.Hashtable<String, Tag>();
    for (Tag t : getAllTags()) {
      tagHashtable.put(t.toString(), t);
    }
    attHashtable = new java.util.Hashtable<String, Attribute>();
    for (Attribute a : getAllAttributeKeys()) {
      attHashtable.put(a.toString(), a);
    }
  }


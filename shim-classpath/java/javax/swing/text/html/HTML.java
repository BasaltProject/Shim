  public static Tag getTag(String tagName) {
    init();
    Tag t = tagHashtable.get(tagName);
    return t == null ? null : t;
  }

  static Tag getTagForName(String tagName) { return getTag(tagName); }

  public static Attribute[] getAllAttributeKeys() { return Attribute.ALL.clone(); }

  public static Attribute getAttributeKey(String attName) {
    init();
    Attribute a = attHashtable.get(attName);
    if (a == null) {
      return null;
    }
    return a;
  }

  public static int getIntegerAttributeValue(javax.swing.text.AttributeSet attr, Attribute key, int def) {
    int value = def;
    String istr = (String) attr.getAttribute(key);
    if (istr != null) {
      try {
        value = Integer.valueOf(istr).intValue();
      } catch (NumberFormatException e) {
        value = def;
      }
    }
    return value;
  }
